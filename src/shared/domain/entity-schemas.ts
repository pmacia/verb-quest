const string = { type: 'string', minLength: 1 };
const boolean = { type: 'boolean' };
const instant = { type: 'string', format: 'date-time' };
const date = { type: 'string', format: 'date' };
const nullable = (schema: object) => ({ anyOf: [schema, { type: 'null' }] });
const enumeration = (...values: string[]) => ({ enum: values });
const array = (items: object) => ({ type: 'array', items });
const object = (properties: Record<string, unknown>, optional: string[] = []) => ({
  type: 'object',
  properties,
  required: Object.keys(properties).filter((k) => !optional.includes(k)),
  additionalProperties: false,
});
const skill = enumeration('recognition', 'recall', 'listening', 'spelling', 'context');
const form = enumeration('base', 'pastSimple', 'pastParticiple');
export const questionSchema = object(
  {
    id: string,
    version: string,
    verbId: string,
    contentVersion: string,
    coverageVersion: string,
    matchingPairs: array(
      object({
        id: string,
        left: string,
        right: string,
        acceptedAnswers: { ...array(string), minItems: 1 },
        coverageTargetIds: { ...array(string), minItems: 1 },
        target: form,
      }),
    ),
    mode: enumeration(
      'flashcards',
      'matching',
      'quiz',
      'audio_detective',
      'sentence_gap',
      'written_recall',
    ),
    skill,
    target: form,
    coverageTargetIds: { ...array(string), minItems: 1 },
    prompt: string,
    acceptedAnswers: { ...array(string), minItems: 1 },
    options: array(string),
    explanation: { type: 'string' },
    audioText: string,
    visualPrompt: string,
    evidenceKind: enumeration('objective', 'self_report'),
    isWritten: boolean,
    retryOf: string,
  },
  ['audioText', 'visualPrompt', 'retryOf', 'coverageVersion', 'matchingPairs'],
);
